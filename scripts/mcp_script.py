#!/usr/bin/env python3
"""Bundle and deploy the read-only MCP server (edge/mcp/) as one Bunny Edge Script.

    python3 scripts/mcp_script.py --out mcp-script/mcp.ts       bundles, changes nothing (verify job)
    python3 scripts/mcp_script.py --deploy mcp-script/mcp.ts    uploads and publishes (publish job, main only)

Bunny takes one file, so the bundle inlines the entry point's relative imports; URL imports stay
as they are and Bunny's Deno runtime loads them. --deploy needs BUNNY_MCP_SCRIPT_ID and
BUNNY_MCP_DEPLOY_KEY, the script's own deployment key (Script > Deployments > Settings), never the
account key.
API: https://docs.bunny.net/api-reference/scripting/code/set-code
"""
import argparse, json, os, re
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
ENTRY = ROOT / "edge/mcp/main.ts"
API = "https://api.bunny.net"
RELATIVE = re.compile(r'^import\s+\{[^}]*\}\s+from\s+"(\./[^"]+)";\s*$', re.M)
ANY_IMPORT = re.compile(r"^\s*import\s", re.M)


def bundle(entry=ENTRY):
    main = entry.read_text()
    modules = []
    for path in RELATIVE.findall(main):
        source = (entry.parent / path).read_text()
        if ANY_IMPORT.search(source):
            raise SystemExit(f"{path} has imports of its own; extend the bundler before deploying")
        modules.append(f"// ---- {path} ----\n{source.rstrip()}\n")
    rest = RELATIVE.sub("", main)
    if re.search(r'from\s+"\.', rest):
        raise SystemExit("Unsupported relative import form in the MCP entry point")
    urls = "".join(line + "\n" for line in rest.splitlines() if line.startswith("import "))
    body = "\n".join(line for line in rest.splitlines() if not line.startswith("import "))
    return f"// Generated by scripts/mcp_script.py from edge/mcp/. Do not edit.\n{urls}\n{''.join(modules)}\n// ---- ./main.ts ----\n{body.strip()}\n"


def call(path, key, body=None):
    data = body.encode() if body is not None else None
    request = Request(API + path, data=data, method="POST",
                      headers={"DeploymentKey": key, "Content-Type": "application/json", "Accept": "application/json"})
    try:
        with urlopen(request, timeout=30):
            pass
    except HTTPError as error:
        raise SystemExit(f"Bunny API POST {path}: {error.code} {error.read()[:300].decode(errors='replace')}") from None


def deploy(code, script_id, key):
    if not re.fullmatch(r"\d+", script_id):
        raise SystemExit("Invalid MCP script ID")
    call(f"/compute/script/{script_id}/code", key, json.dumps({"Code": code}))
    call(f"/compute/script/{script_id}/publish", key)
    print(f"MCP edge script {script_id} uploaded and published ({len(code.encode())} bytes).")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out", type=Path)
    group.add_argument("--deploy", type=Path)
    args = parser.parse_args()
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(bundle())
        print(f"Bundled the MCP server into {args.out}.")
    else:
        if not (os.environ.get("RELEASE_EVENT") == "push" and os.environ.get("RELEASE_REF") == "refs/heads/main"):
            raise SystemExit("Deploying the production MCP script requires a main-branch push")
        deploy(args.deploy.read_text(), os.environ["BUNNY_MCP_SCRIPT_ID"], os.environ["BUNNY_MCP_DEPLOY_KEY"])
